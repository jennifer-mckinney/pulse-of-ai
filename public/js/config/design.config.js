// PulseDesignConfig — design tokens for the Pulse of AI frontend (DATA ONLY).
// Every value is ported from the design handoff README "Design Tokens"
// section (design_handoff_pulse_of_ai/README.md) unless commented otherwise.
// Zero functions by contract — logic that consumes these tokens lives in
// utils.js / globe / story modules. Structural invariants are locked by
// tests/unit/pure/config.test.js.
//
// Dual export guard: CommonJS (module.exports) for jest,
// window.PulseDesignConfig for browser script tags (same pattern as utils.js).
(function (root, factory) {
    if (typeof module === 'object' && module.exports) {
        module.exports = factory();              // Node / jest
    } else {
        /* istanbul ignore next -- Browser UMD global; unreachable in Node tests */
        root.PulseDesignConfig = factory();      // browser global
    }
}(typeof self !== 'undefined' ? self : this, function () {
    'use strict';

    // Deep-freeze: config is shared, data-only state — a consumer mutating a
    // token table would silently corrupt every other module. Frozen exports
    // make mutation attempts throw in strict mode instead.
    function deepFreeze(node) {
        if (node && typeof node === 'object' && !Object.isFrozen(node)) {
            Object.freeze(node);
            for (const key of Object.keys(node)) deepFreeze(node[key]);
        }
        return node;
    }

    // ── Themes (CSS custom-property sets, switchable at runtime) ────────────
    // Verbatim from the handoff README theme table. panelRgb feeds
    // `--panel: rgba(var(--panel-rgb), var(--panel-alpha))`.
    const THEMES = {
        Midnight: {
            bg: '#06090F',
            ink: '#E8EDF4',
            inkDim: '#93A0B4',
            line: 'rgba(140,165,205,0.14)',
            panelRgb: '13,19,30',
            accent: '#3BDCB2',
        },
        Void: {
            bg: '#000000',
            ink: '#EDEDF0',
            inkDim: '#8E8E9A',
            line: 'rgba(180,180,200,0.13)',
            panelRgb: '10,10,13',
            accent: '#4EA8FF',
        },
        Ember: {
            bg: '#0C0806',
            ink: '#F2EAE2',
            inkDim: '#A89A8C',
            line: 'rgba(220,180,140,0.14)',
            panelRgb: '24,16,11',
            accent: '#FFB454',
        },
    };

    const DEFAULT_THEME = 'Midnight';

    // ── Sentiment palette (default handoff palette: neg / neu / pos) ────────
    const SENTIMENT_PALETTE = {
        negative: '#FF6E5E',
        neutral:  '#7E8AA0',
        positive: '#3BDCB2',
    };

    // ── Canonical category registry (prototype taxonomy ∪ BRD/PRD §17) ─────
    // THE single source of truth for the source-category taxonomy, shared by
    // BOTH sides of the stack (same pattern as cities.config.js — the backend
    // consumes it via src/config/categories.js). The frontend prototype
    // (exported-assets/prototype-globe-artifact) is the master contract:
    // its 7 rendered categories (Social, News, Academic, Policy, Developer,
    // Forums, Blogs) union the BRD/PRD §17 seven (…non-profits…) give the
    // canonical EIGHT. Slugs are the data_sources.category API values;
    // labels are the prototype's EXACT display strings — 'Blogs' (plural)
    // and 'Non-profit' (hyphenated) are deliberate and must NEVER be
    // regenerated by naive capitalization of the slug (that would render
    // "Blog"/"Nonprofit"). Order: spec §17 order with Forums inserted before
    // Blogs, matching the prototype's Developer → Forums → Blogs tail.
    // Colors are the prototype's CAT_COLORS verbatim; Non-profit has no
    // prototype hue (the prototype never rendered it), so it takes ONE new
    // palette-consistent color: #A9F55A, a lime in the handoff palette's
    // saturation/lightness family (same F5/5A channel pattern as the Forums
    // yellow #F5D95A), hue ~90° — distinct from every prototype category hue
    // (orange 28°, yellow 49°, teal 164°, cyan 194°, blue 213°, purple 271°,
    // pink 341°) and from the severity greens (#3BDC7E 145°, #3BDCB2 164°).
    // Enumeration surfaces — explore chips, the CH05 category legend, the
    // source ribbon, /api/sources/timeseries and the "categories tracked"
    // copy — render from THIS list (via insights.allCategoryRows / the
    // backend canon config), never from whichever categories happen to have
    // posts in the window, so quiet categories (forums has zero live
    // sources by design) stay visible as honest zeros.
    const CATEGORIES = [
        { slug: 'social',    label: 'Social',     color: '#FF9F5A' },
        { slug: 'news',      label: 'News',       color: '#5AA9FF' },
        { slug: 'academic',  label: 'Academic',   color: '#C08BFF' },
        { slug: 'policy',    label: 'Policy',     color: '#FF6E9C' },
        { slug: 'nonprofit', label: 'Non-profit', color: '#A9F55A' },
        { slug: 'developer', label: 'Developer',  color: '#3BDCB2' },
        { slug: 'forums',    label: 'Forums',     color: '#F5D95A' },
        { slug: 'blog',      label: 'Blogs',      color: '#7EE0FF' },
    ];

    // Derived lookup tables (data derivation, not logic — consumers keep
    // reading the same CAT_COLORS shape as before; CATEGORY_SLUGS preserves
    // registry order for enumeration/rotation consumers). The legacy 'tech'
    // slug is GONE: forums is a first-class canonical slug now, and residual
    // tech-categorized data maps to developer (migration 007 backend-side,
    // globe.js normalizeCategorySlug frontend-side).
    const CATEGORY_SLUGS = [];
    const CAT_LABELS = {};
    const CAT_COLORS = {};
    for (const c of CATEGORIES) {
        CATEGORY_SLUGS.push(c.slug);
        CAT_LABELS[c.slug] = c.label;
        CAT_COLORS[c.slug] = c.color;
    }

    // ── Severity colors (bias/health drawer) ────────────────────────────────
    const SEVERITY_COLORS = {
        alert: '#FF6E5E',
        watch: '#F5C36B',
        pass:  '#3BDC7E',
    };

    // ── Sentiment bucket thresholds ─────────────────────────────────────────
    // Partitioned buckets over NET sentiment ((positive − negative) / total):
    //   net >  positiveMin → 'positive'
    //   net <  negativeMax → 'negative'
    //   otherwise          → 'neutral'
    // This deliberately FIXES the prototype's overlapping buckets (it used
    // >= 0.1 warm AND < 0.1 cold in one place, >= 0 positive elsewhere) —
    // here the three ranges partition the axis with no overlap and no gap.
    const SENTIMENT_BUCKETS = {
        positiveMin: 0.1,
        negativeMax: -0.1,
    };

    // ── Globe behavior constants ────────────────────────────────────────────
    const GLOBE = {
        spinPeriodMs: 300000,     // ~5 min per revolution at speed 1 (handoff-verified)
        ringPeriodMs: 2200,       // city pulse-ring expansion period
        idleResumeMs: 3000,       // auto-rotation resumes this long after a drag
                                  // (also the user-zoom override window)
        labelVolumeMin: 230,      // explore mode labels cities above this volume
        pacingVhPerChapter: 1.15, // scroll spacer: 1.15 × 100vh per chapter
        // User zoom (handoff ZIP revision; audit gap G7). globe.js composes
        // userZoom with the chapter zoom: target = chapterZoom × userZoom.
        userZoomMin: 0.5,         // pinch/wheel/keyboard zoom clamp floor
        userZoomMax: 3.5,         // pinch/wheel/keyboard zoom clamp ceiling
        wheelZoomCtrlFactor: 0.01,   // exp(−deltaY × this) for ctrl-wheel/pinch-trackpad
        wheelZoomPlainFactor: 0.002, // plain wheel factor (explore mode only)
        keyZoomStep: 1.15,        // "+" multiplies, "−" divides; "0" resets to 1
    };

    return deepFreeze({
        THEMES,
        DEFAULT_THEME,
        SENTIMENT_PALETTE,
        CAT_COLORS,
        CAT_LABELS,
        CATEGORIES,
        CATEGORY_SLUGS,
        SEVERITY_COLORS,
        SENTIMENT_BUCKETS,
        GLOBE,
    });
}));
