WITH open_alerts AS (
    SELECT ae.id, ae.alert_type, (ae.details->>'jobId')::uuid AS job_id
    FROM alert_events ae
    WHERE ae.alert_type IN ('location_concentration', 'platform_sentiment_parity', 'negative_dominance')
      AND ae.resolved_at IS NULL
      AND ae.details->>'jobId' ~ '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'
      AND NOT EXISTS (SELECT 1 FROM alert_resolutions r WHERE r.alert_id = ae.id)
),
job_posts AS (
    SELECT DISTINCT oa.id AS alert_id, rp.id AS post_id, rp.location, ds.category,
           COALESCE(rp.raw_payload->>'location_basis', 'content') AS basis,
           sr.comparative, sr.indicator
    FROM open_alerts oa
    JOIN decision_audit_log d ON d.job_id = oa.job_id AND d.decision_type = 'sentiment'
    JOIN raw_posts rp ON rp.id = d.raw_post_id
    JOIN data_sources ds ON ds.id = rp.source_id
    LEFT JOIN sentiment_results sr ON sr.raw_post_id = rp.id
),
loc_city AS (
    SELECT alert_id, location, COUNT(*)::int AS n FROM job_posts
    WHERE location IS NOT NULL AND location <> '' AND basis <> 'publisher'
    GROUP BY alert_id, location
),
loc AS (
    SELECT oa.id AS alert_id,
           COALESCE((SELECT SUM(n) FROM loc_city c WHERE c.alert_id = oa.id), 0)::int AS sample,
           COALESCE((SELECT MAX(n) FROM loc_city c WHERE c.alert_id = oa.id), 0)::int AS dominant,
           (SELECT COUNT(*) FROM job_posts jp WHERE jp.alert_id = oa.id AND jp.location <> '' AND jp.basis = 'publisher')::int AS excluded
    FROM open_alerts oa WHERE oa.alert_type = 'location_concentration'
),
par_cat AS (
    SELECT alert_id, category, COUNT(*)::int AS n, AVG(comparative) AS avg_c
    FROM job_posts WHERE comparative IS NOT NULL GROUP BY alert_id, category
),
par AS (
    SELECT oa.id AS alert_id,
           (SELECT COUNT(*) FROM par_cat p WHERE p.alert_id = oa.id AND p.n >= 10)::int AS qualifying,
           (SELECT MAX(avg_c) - MIN(avg_c) FROM par_cat p WHERE p.alert_id = oa.id AND p.n >= 10) AS max_diff
    FROM open_alerts oa WHERE oa.alert_type = 'platform_sentiment_parity'
),
neg AS (
    SELECT oa.id AS alert_id,
           (SELECT COUNT(*) FROM job_posts jp WHERE jp.alert_id = oa.id AND jp.indicator IS NOT NULL)::int AS sample,
           (SELECT COUNT(*) FROM job_posts jp WHERE jp.alert_id = oa.id AND jp.indicator = 'negative')::int AS negatives
    FROM open_alerts oa WHERE oa.alert_type = 'negative_dominance'
),
stale AS (
    SELECT oa.id AS alert_id, oa.job_id, oa.alert_type,
           CASE WHEN l.sample < 30 THEN 'insufficient sample'
                ELSE 'within threshold once publisher-located posts are excluded' END AS verdict,
           jsonb_build_object('content_located_posts', l.sample, 'publisher_located_posts_excluded', l.excluded,
                              'dominant_city_posts', l.dominant, 'min_sample', 30, 'threshold', 0.35) AS evidence
    FROM open_alerts oa JOIN loc l ON l.alert_id = oa.id
    WHERE l.sample < 30 OR l.dominant::float8 / NULLIF(l.sample, 0) <= 0.35
    UNION ALL
    SELECT oa.id, oa.job_id, oa.alert_type,
           CASE WHEN p.qualifying < 2 THEN 'insufficient sample' ELSE 'within threshold' END,
           jsonb_build_object('categories_with_min_posts', p.qualifying, 'min_per_category', 10,
                              'max_comparative_diff', p.max_diff, 'threshold', 0.30)
    FROM open_alerts oa JOIN par p ON p.alert_id = oa.id
    WHERE p.qualifying < 2 OR p.max_diff <= 0.30
    UNION ALL
    SELECT oa.id, oa.job_id, oa.alert_type,
           CASE WHEN n.sample < 30 THEN 'insufficient sample' ELSE 'within threshold' END,
           jsonb_build_object('posts', n.sample, 'negative_posts', n.negatives, 'min_sample', 30, 'threshold', 0.60)
    FROM open_alerts oa JOIN neg n ON n.alert_id = oa.id
    WHERE n.sample < 30 OR n.negatives::float8 / NULLIF(n.sample, 0) <= 0.60
),
recorded AS (
    INSERT INTO alert_resolutions (alert_id, resolved_by, resolution, basis, methodology_version_id)
    SELECT s.alert_id,
           'migration 032_bias_sample_rules.sql',
           'Superseded by bias@1.4.0: ' || s.verdict || ' (' || s.alert_type || '); the alert measured the size of one '
               || 'collection cycle, not the discourse.',
           s.evidence || jsonb_build_object('job_id', s.job_id, 'methodology', 'bias@1.4.0', 'verdict', s.verdict),
           (SELECT id FROM methodology_versions WHERE component = 'bias' AND version = '1.4.0')
    FROM stale s
    ON CONFLICT (alert_id) DO NOTHING
    RETURNING id, alert_id
)
UPDATE alert_events ae
SET resolved_at = NOW(),
    details = CASE WHEN COALESCE(ae.details, '{}'::jsonb) ? 'resolution_ref' THEN ae.details
                   ELSE COALESCE(ae.details, '{}'::jsonb)
                        || jsonb_build_object('resolution_ref', 'alert_resolutions ' || r.id::text || ' (migration 032, bias@1.4.0)') END
FROM recorded r
WHERE ae.id = r.alert_id AND ae.resolved_at IS NULL;
