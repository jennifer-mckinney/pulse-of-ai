-- Migration 032: bias@1.4.0 — a minimum sample for EVERY fairness check —
-- and an audited resolution of every open bias alert it would not raise.
--
-- Jennifer's live dashboard (2026-09-29) showed 39 active alerts, 31
-- critical: location concentration 1.000 for single publisher cities, and
-- demographic-parity watches between categories of a few posts, from
-- collection cycles of a handful of posts. bias@1.4.0 (src/pipeline/bias.js):
--   location concentration  >= 30 content-located posts, publisher-located
--                           posts excluded (bias@1.2.0/1.3.0, decision D3)
--   platform sentiment parity  only categories with >= 10 posts compared;
--                           fewer than two such categories: insufficient
--   negative dominance      >= 30 posts
-- Below a minimum: "insufficient sample", no violation, no alert.
--
-- 1. alert_resolutions.methodology_version_id (created by 028; added here
--    only for a database that ran an earlier draft of 028). No existing
--    resolution row is ever updated (PR #22 principal #9).
-- 2. bias@1.4.0 is registered (generated by
--      node scripts/generate-methodology-migration.js bias@1.4.0
--    and mirroring src/config/methodology-registry.js field for field).
-- 3. Every OPEN location_concentration, platform_sentiment_parity and
--    negative_dominance alert is re-evaluated from the stored rows of its
--    job under bias@1.4.0's rules; those it would not raise get an
--    alert_resolutions row (who, why, the evidence, the version) and
--    resolved_at plus details.resolution_ref (only when absent) on the
--    alert. The original alert
--    and bias_assessments rows are never deleted or rewritten otherwise; an
--    alert whose job still fails the rules stays open. Idempotent.

ALTER TABLE alert_resolutions ADD COLUMN IF NOT EXISTS methodology_version_id UUID REFERENCES methodology_versions(id);

